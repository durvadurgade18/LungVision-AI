// ------------------------------------------------------------
// 1. LOAD PREDICTION FROM SESSION STORAGE
//    (saved by predict.js as "lungVisionCouponData")
// ------------------------------------------------------------

function loadCoupon() {

    const raw = sessionStorage.getItem("lungVisionCouponData");

    if (!raw) {

        document.querySelector(".card").innerHTML = `

            <div style="
                padding:50px;
                text-align:center;
                width:100%;
                color:#6b7280;
                font-family:Arial;
            ">

                <div style="font-size:55px;margin-bottom:15px;">
                    🫁
                </div>

                <h2 style="color:#0a1e42;margin-bottom:10px;">
                    No Prediction Found
                </h2>

                <p>
                    Please analyze an X-ray first before
                    generating a coupon.
                </p>

            </div>

        `;

        return;
    }

    let data;

    try {
        data = JSON.parse(raw);
    }
    catch (err) {
        console.error("Invalid stored prediction data:", err);
        return;
    }

    // renderCoupon({

    //     patientName: data.patientName || "Guest",
    //     email: data.email || "—",
    //     predictedResult: data.disease,
    //     confidence: data.confidence,

        renderCoupon({

    patientName: (window.LUNGVISION_USER && window.LUNGVISION_USER.patientName) || "Guest",
    email: (window.LUNGVISION_USER && window.LUNGVISION_USER.patientEmail) || "—",
    predictedResult: data.disease,
    confidence: data.confidence,

        validFrom: new Date(),
        validDays: 7,
        discountPercent: 50,
        status: "ACTIVE"

    });

}



// ------------------------------------------------------------
// 2. DATE FORMATTER
// ------------------------------------------------------------

function formatDate(date) {

    return date.toLocaleDateString(
        "en-GB",
        {
            day: "2-digit",
            month: "short",
            year: "numeric"
        }
    );

}



// ------------------------------------------------------------
// 3. GENERATE COUPON ID
// ------------------------------------------------------------
//
// Example:
// LVA-20260811-A7K9P2
//
// NOTE:
// For true database-level uniqueness, this should
// eventually be generated by your Python backend.
// ------------------------------------------------------------

function generateCouponId() {

    const datePart =
        new Date()
        .toISOString()
        .slice(0, 10)
        .replace(/-/g, "");


    const randomPart =
        crypto.randomUUID()
        .replace(/-/g, "")
        .substring(0, 8)
        .toUpperCase();


    return `LVA-${datePart}-${randomPart}`;

}



// ------------------------------------------------------------
// 4. ADD DAYS TO DATE
// ------------------------------------------------------------

function addDays(date, days) {

    const result =
        new Date(date);

    result.setDate(
        result.getDate() + days
    );

    return result;

}



// ------------------------------------------------------------
// 5. RENDER COUPON
// ------------------------------------------------------------

function renderCoupon(data) {


    // --------------------------------------------------------
    // CONFIDENCE CHECK
    // --------------------------------------------------------

    if (
        data.confidence == null ||
        Number(data.confidence) <= 85
    ) {

        document.querySelector(".card").innerHTML = `

            <div style="
                padding:50px;
                text-align:center;
                width:100%;
                font-family:Arial;
            ">

                <div style="font-size:55px;margin-bottom:15px;">
                    🫁
                </div>

                <h2 style="color:#0a1e42;margin-bottom:10px;">
                    Coupon Not Available
                </h2>

                <p style="color:#6b7280;font-size:15px;">
                    Your prediction confidence is
                    85% or below.
                </p>

                <p style="color:#6b7280;font-size:14px;">
                    A LungVision AI coupon is issued
                    only when prediction confidence
                    is greater than 85%.
                </p>

            </div>

        `;

        return;
    }



    // --------------------------------------------------------
    // VALIDITY
    // --------------------------------------------------------

    const validFrom =
        data.validFrom
            ? new Date(data.validFrom)
            : new Date();


    const validUntil =
        addDays(validFrom, 7);



    // --------------------------------------------------------
    // UNIQUE COUPON ID
    // --------------------------------------------------------

    const couponId =
        data.couponId ||
        generateCouponId();



    // --------------------------------------------------------
    // DISCOUNT
    // --------------------------------------------------------

    const discount = 50;



    // --------------------------------------------------------
    // PATIENT INFORMATION
    // --------------------------------------------------------

    document.getElementById("fName").textContent =
        data.patientName || "—";

    document.getElementById("fEmail").textContent =
        data.email || "—";



    // --------------------------------------------------------
    // PREDICTION INFORMATION
    // --------------------------------------------------------

    document.getElementById("fResult").textContent =
        data.predictedResult || "—";

    document.getElementById("fConf").textContent =
        `${data.confidence}%`;



    // --------------------------------------------------------
    // DATE INFORMATION
    // --------------------------------------------------------

    document.getElementById("fFrom").textContent =
        formatDate(validFrom);

    document.getElementById("fUntil").textContent =
        formatDate(validUntil);



    // --------------------------------------------------------
    // COUPON STATUS
    // --------------------------------------------------------

    const status = data.status || "ACTIVE";

    const statusElement =
        document.getElementById("fStatus");

    statusElement.textContent = status;



    // --------------------------------------------------------
    // DISCOUNT DISPLAY
    // --------------------------------------------------------

    document.getElementById("fDiscount").textContent =
        discount;

    const rightDiscount =
        document.getElementById("fDiscountRight");

    if (rightDiscount) {
        rightDiscount.textContent = discount;
    }



    // --------------------------------------------------------
    // COUPON ID DISPLAY
    // --------------------------------------------------------

    document.getElementById("fCouponId").textContent =
        couponId;



    // --------------------------------------------------------
    // STATUS COLOR
    // --------------------------------------------------------

    if (status === "ACTIVE") {
        statusElement.style.background = "#e4f8ec";
        statusElement.style.color = "#1fa25a";
    }
    else if (status === "EXPIRED") {
        statusElement.style.background = "#fde8e8";
        statusElement.style.color = "#d64545";
    }
    else if (status === "USED") {
        statusElement.style.background = "#fff1d6";
        statusElement.style.color = "#b7791f";
    }
    else {
        statusElement.style.background = "#eef0f4";
        statusElement.style.color = "#6b7280";
    }



    // --------------------------------------------------------
    // QR CODE
    // --------------------------------------------------------

    const qrContainer =
        document.getElementById("qrcode");

    qrContainer.innerHTML = "";

    // const verifyBaseUrl =
    //     data.verifyBaseUrl ||
    //     "http://localhost:5000/verify-coupon?couponId=";
        const verifyBaseUrl =
    data.verifyBaseUrl ||
    "http://10.138.10.188:5000/verify-coupon?couponId="; 

    const verificationUrl =
        verifyBaseUrl + encodeURIComponent(couponId);

    new QRCode(
        qrContainer,
        {
            text: verificationUrl,
            width: 70,
            height: 70,
            colorDark: "#0a1e42",
            colorLight: "#ffffff"
        }
    );

}



// ------------------------------------------------------------
// 6. START WHEN PAGE LOADS
// ------------------------------------------------------------

document.addEventListener(
    "DOMContentLoaded",
    loadCoupon
);